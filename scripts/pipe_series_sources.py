#!/usr/bin/env python3
"""Writes pipe-series-sources.md from the generated manufacturer series index.

The index (pipeSeriesIndex.generated.json) is produced by the pipe seed generator of the UI repository from
its evidence table. Nothing in the output is typed by hand: re-run this script after the index changes.

Usage:
  python3 scripts/pipe_series_sources.py INDEX.json            rewrite pipe-series-sources.md
  python3 scripts/pipe_series_sources.py INDEX.json --check    exit 1 when the file is not what the index gives
"""
import json
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "pipe-series-sources.md"


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def render(index):
    makers = {m["code"]: m for m in index["makers"]}
    docs = index["documents"]
    series = index["series"]
    rows = sum(s["rows"] for s in series)
    out = [
        "# Pipe manufacturer series, sources",
        "",
        "Generated by `scripts/pipe_series_sources.py` from the generated series index of the pipe seed generator. "
        "Do not edit by hand.",
        "",
        "EnergyFlowX is not affiliated with, sponsored by, or endorsed by any manufacturer listed here. "
        "The name says whose catalogue the sizes come from. The dimensions are the manufacturer's printed "
        "catalogue values as read on the access date, so check them against the current catalogue and the "
        "delivered product before you rely on them. A designation is shown only as the manufacturer's document "
        "prints it.",
        "",
        f"{len(series)} series from {len({s['maker'] for s in series})} manufacturers, "
        f"{rows} printed size and wall rows, {len(docs)} documents. Documents read on {index['accessDate']}.",
        "",
        "| Manufacturer | Series | Product line as printed | Designation as printed | Document | Access date |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for s in series:
        m = makers[s["maker"]]
        texts = ", ".join(dict.fromkeys(d["text"] for d in s["designations"]))
        desig = f"Listed as {texts} by {m['name']}" if texts else "none printed"
        links = []
        dates = []
        for key in s["documents"]:
            d = docs[key]
            links.append(f"[{cell(d['title'])}]({d['url']})")
            dates.append(d["accessed"])
        out.append(
            f"| {cell(m['name'])} | {cell(s['code'])} | {cell(s['productName'])} | {cell(desig)} | "
            f"{'; '.join(links)} | {', '.join(dict.fromkeys(dates))} |"
        )
    return "\n".join(out) + "\n"


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    text = render(json.loads(Path(argv[1]).read_text(encoding="utf-8")))
    if "--check" in argv:
        return 0 if OUT.exists() and OUT.read_text(encoding="utf-8") == text else 1
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
